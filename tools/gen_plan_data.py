#!/usr/bin/env python3
"""Emit bench/plan_data.tsp: everything the instrument's plan draw cannot derive for itself.

WHY GENERATED, AND WHY THIS IS THE WHOLE SAFETY ARGUMENT. bench/plan_gen.tsp draws the soak plan on
the instrument so the bench app needs no host. soakplan.py draws the same plan on the Mac. Two
implementations of one draw is the failure plan_order's own comment describes -- two different laps
being compared, silently -- and the defence is that the DATA both of them key on comes from one
place. This file emits it FROM soakplan.py itself, so the vector order, the manifest spans and every
constant are the host's own values by construction rather than by a reader checking two lists.

tools/test_plan_gen.lua asserts this file is current AND that the two draws agree byte for byte, so
a vector added to vector_names.py without regenerating here fails offline rather than on a lap.

WHAT IS NOT HERE, DELIBERATELY. sdec.rates, sdec.stdbaud and sdec.flatfloor are LIVE on the
instrument, and soakplan.py reads those same three out of tsp/serial_core.tsp rather than copying
them. Emitting them would create the copy both sides exist to avoid: tune the ladder in tsp/ and a
generated snapshot would quietly draw against the old one. The instrument reads sdec; the host reads
the file; there is one source.

THE VECTOR ORDER IS THE LOAD-BEARING PART. `vi` is a vector's position in the list AFTER the skip and
BEFORE the shuffle, and vi keys the amplitude, the offset and the wait of every cell it owns. A list
differing by one entry is a different experiment wearing the same name -- measured once at 1677 of
1677 cells. So the list is emitted in soak_vectors() order and the test compares plans, not lists.

    python3 tools/gen_plan_data.py            # rewrite bench/plan_data.tsp
    python3 tools/gen_plan_data.py --check     # exit 1 if it is stale, printing what moved
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import soakplan as SP                                                   # noqa: E402
import instruments as _I                                               # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'bench', 'plan_data.tsp')

HEADER = """\
-- plan_data.tsp -- GENERATED by tools/gen_plan_data.py. Do not edit; run that instead.
--
-- The data the on-instrument plan draw cannot derive: the soak's vector list in the order the draw
-- keys on, each vector's manifest span, and soakplan.py's own constants. Emitted from soakplan.py so
-- both draws key on one set of numbers -- see that tool's header for why a second copy is unsafe.
--
-- NOT HERE ON PURPOSE: the rate ladder, the standard rates and the flat floor. Those are live in
-- sdec on the instrument and read out of tsp/serial_core.tsp on the host, so neither side holds a
-- copy that can go stale.
--
-- tools/test_plan_gen.lua asserts this file is current and that the two draws agree byte for byte.

bplan = bplan or {}

"""


def _rows():
    return SP._manifest_rows()


def body():
    vecs = SP.soak_vectors()
    rv = SP.random_vectors()
    out = [HEADER]

    # THE ORDER IS THE DATA. Emitted as a sequence, not a set, because vi is a position.
    out.append('-- The soak\'s vectors, in soak_vectors() order. vi is a position in this list.\n')
    out.append('bplan.vecs = {\n')
    for i in range(0, len(vecs), 8):
        out.append('  ' + ', '.join("'%s'" % v for v in vecs[i:i + 8]) + ',\n')
    out.append('}\n\n')

    out.append('-- The random-payload vectors the per-lap subset draws from, sorted.\n')
    out.append('bplan.rvecs = {' + ', '.join("'%s'" % v for v in rv) + '}\n\n')

    out.append('-- The vectors every hardware lap leaves out.\n')
    out.append('bplan.hwskip = {' + ', '.join("'%s'" % v for v in SP.HW_SKIP) + '}\n\n')

    # PER VECTOR: the four manifest numbers amp_ofst_for keys on, the samples-a-bit the sample rate
    # comes from, and whether the vector has expected bytes at all -- a vector with none is skipped
    # by emit_csv, which changes the CELL COUNT and not merely an outcome.
    out.append('-- amp: reference Vpp.  ofst: reference offset.  lo/hi: the rendered extremes in\n'
               '-- volts.  spb: samples a bit, which sets the generator rate.  exp: has expected\n'
               '-- bytes, and a vector without them is not drawn at all.\n')
    out.append('bplan.span = {}\n')
    rows = _rows()
    for v in vecs:
        r = rows.get(v) or {}
        amp = float(r.get('amp_vpp') or 10.0)
        ofst = float(r.get('ofst_v') or 0.0)
        lo = float(r.get('min_v') or 0.0)
        hi = float(r.get('max_v') or 0.0)
        spb = int(r.get('spb') or 10)
        exp = 1 if (r.get('exp_hex') or '').strip() else 0
        # %.17g ROUND-TRIPS A DOUBLE. These feed an arithmetic chain whose output is compared byte
        # for byte against the host's, so a shortened literal is a different number.
        out.append("bplan.span['%s'] = {amp = %.17g, ofst = %.17g, lo = %.17g, hi = %.17g, "
                   "spb = %d, exp = %d}\n" % (v, amp, ofst, lo, hi, spb, exp))
    out.append('\n')

    # soakplan.py's OWN constants. The draw's shape lives there, so these are emitted rather than
    # typed: changing SWING_HI in one place must not leave the instrument drawing the old envelope.
    out.append('-- soakplan.py\'s constants, emitted so the two draws cannot disagree on them.\n')
    out.append('bplan.k = {magic = %d, order = %d, rate = %d, wait = %d, amp = %d, ofst = %d, '
               'rsub = %d}\n' % (SP.MAGIC, SP.P_ORDER, SP.P_RATE, SP.P_WAIT, SP.P_AMP, SP.P_OFST,
                                 SP.P_RSUB))
    out.append('bplan.c = {\n')
    for name, val, fmt in (
            ('swinglo', SP.SWING_LO, '%.17g'), ('swinghi', SP.SWING_HI, '%.17g'),
            ('sdgmax', SP.SDG_MAX_VPP, '%.17g'), ('vrail', SP.V_RAIL, '%.17g'),
            ('env', SP.SDG_ENV_V, '%.17g'), ('qdig', SP.Q_DIGITS, '%d'),
            ('baudlo', SP.BAUD_LO, '%d'), ('baudhi', SP.BAUD_HI, '%d'),
            ('waitbt', SP.WAIT_BYTE_TIMES, '%.17g'), ('bitsbyte', SP.BITS_PER_BYTE, '%.17g'),
            ('edgeodds', SP.EDGE_ODDS, '%d'), ('interlo', SP.INTERSTITIAL_LO, '%d'),
            ('srmax', _I.SDG_MAX_SRATE, '%.17g')):
        out.append(('  %s = ' + fmt + ',\n') % (name, val))
    out.append('}\n\n')
    out.append('-- The standard rates soakplan drops from the draw, as a lookup.\n')
    out.append('bplan.bauddrop = {}\n')
    for b in SP.BAUD_DROP:
        out.append('bplan.bauddrop[%d] = true\n' % b)
    return ''.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true',
                    help='exit 1 if bench/plan_data.tsp is not what this would write')
    a = ap.parse_args()
    want = body()
    have = open(OUT).read() if os.path.exists(OUT) else None
    if a.check:
        if have == want:
            print('bench/plan_data.tsp is current (%d vectors)' % len(SP.soak_vectors()))
            return 0
        print('bench/plan_data.tsp is STALE -- rerun tools/gen_plan_data.py')
        if have is None:
            print('  it does not exist at all')
        else:
            hl, wl = have.split('\n'), want.split('\n')
            for i in range(max(len(hl), len(wl))):
                h = hl[i] if i < len(hl) else '<absent>'
                w = wl[i] if i < len(wl) else '<absent>'
                if h != w:
                    print('  line %d\n    on disk: %s\n    should be: %s' % (i + 1, h, w))
                    break
        return 1
    with open(OUT, 'w') as fh:
        fh.write(want)
    print('wrote %s' % os.path.relpath(OUT, ROOT))
    print('  %d vectors, %d random, %d skipped by every hardware lap'
          % (len(SP.soak_vectors()), len(SP.random_vectors()), len(SP.HW_SKIP)))
    return 0


sys.exit(main())
